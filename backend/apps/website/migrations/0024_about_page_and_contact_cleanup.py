    SiteNavItem = apps.get_model("website", "SiteNavItem")

    about, created = SitePage.objects.get_or_create(
        slug="about",
        defaults={
            "title": ABOUT_TITLE,
            "body": ABOUT_BODY,
            "order": 4,
            "show_in_app": True,
            "show_in_footer": True,
        },
    )
    if not created:
        about.title = ABOUT_TITLE
        about.body = ABOUT_BODY
        about.order = 4
        about.show_in_app = True
        about.show_in_footer = True
